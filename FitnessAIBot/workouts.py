import random 
def select_new_exercises(
    exercises: list,
    count: int,
    rng: random.Random,
) -> list:
    """
    Выбирает упражнения для нового варианта программы.
    Не изменяет исходный список.
    """

    if not exercises:
        return []

    exercises_copy = exercises.copy()
    rng.shuffle(exercises_copy)

    return exercises_copy[:min(count, len(exercises_copy))]

def create_workout_program(
    goal: str,
    experience: str,
    place: str,
    days: int,
    variation: int = 0,
) -> str:

    days = max(2, min(days, 6))

    rng = random.Random(
        f"{goal}-{experience}-{place}-{days}-{variation}"
    )

    if "зал" in place.lower():
        workouts = get_gym_workouts()
    else:
        workouts = get_home_workouts()

    weekly_split = get_weekly_split(days)

    sets, reps, rest = get_training_parameters(
        goal,
        experience,
    )

    result = [
        "🏋️ ПРОГРАММА ТРЕНИРОВОК НА НЕДЕЛЮ",
        "",
        f"🎯 Цель: {goal}",
        f"📊 Уровень: {experience}",
        f"📍 Место: {place}",
        f"📅 Тренировок: {days}",
        "",
    ]

    for day_name, workout_name in weekly_split:

        if workout_name == "Отдых":
            result.append(f"{day_name}: Отдых")
            continue

        exercises = workouts.get(workout_name, [])

        selected_exercises = select_new_exercises(
            exercises,
            count=6,
            rng=rng
        )

        result.append(f"{day_name}: {workout_name}")

        for exercise in selected_exercises:
            name = exercise["name"]
            tip = exercise.get("tip", "")
            exercise_sets = exercise.get("sets", sets)
            exercise_reps = exercise.get("reps", reps)
            exercise_rest = exercise.get("rest", rest)

            result.append(
                f"  - {name} ({exercise_sets} подходов по {exercise_reps} повторений, отдых {exercise_rest})"
                + (f" 💡 {tip}" if tip else "")
            )

        result.append("")
        result.extend([
        "━━━━━━━━━━━━━━━━━━",
        "📌 РЕКОМЕНДАЦИИ",
        "",
        "• Перед тренировкой выполняй разминку 5–10 минут.",
        "• Начинай с лёгких разминочных подходов.",
        "• Следи за правильной техникой.",
        "• Увеличивай рабочий вес постепенно.",
        "• После тренировки сделай растяжку.",
        "• Оставляй 1–2 повторения в запасе.",
    ])

    if goal.lower() == "похудение":
        result.append(
            "• После силовой тренировки выполни кардио 15–25 минут."
        )

    elif goal.lower() == "набор":
        result.append(
            "• Для роста мышц соблюдай профицит калорий и потребляй достаточно белка."
        )

    else:
        result.append(
            "• Поддерживай текущую физическую форму, соблюдая режим тренировок и питания."
        )

    return "\n".join(result)

        
def get_training_parameters(
    goal: str,
    experience: str
) -> tuple[str, str, str]:
    """Возвращает стандартные подходы, повторения и отдых."""

    goal = goal.lower()
    experience = experience.lower()

    if goal == "набор":
        reps = "6–10"
        rest = "90–120 секунд"
    elif goal == "похудение":
        reps = "10–15"
        rest = "45–75 секунд"
    else:
        reps = "8–12"
        rest = "60–90 секунд"

    if experience == "новичок":
        sets = "3"
    elif experience == "продвинутый":
        sets = "4"
    else:
        sets = "3–4"

    return sets, reps, rest


