@router.message(F.text == "🧘 Медитация")
async def meditation_start(
    message: Message,
    state: FSMContext,
):

    await state.set_state(
        MeditationForm.goal
    )

    await message.answer(

        "🧘 Добро пожаловать в раздел медитации.\n\n"

        "Для чего хотите медитацию?",

        reply_markup=goal_keyboard,
    )
    
    
    
@router.message(MeditationForm.duration)
async def meditation_duration(
    message: Message,
    state: FSMContext,
):
    text = (message.text or "").strip().lower()

    durations = {
        "5 минут": 5,
        "10 минут": 10,
        "15 минут": 15,
        "20 минут": 20,
      
    }

    if text not in durations:
        await message.answer(
            "⏳ Выберите продолжительность кнопкой ниже.",
            reply_markup=duration_keyboard,
        )
        return

    await state.update_data(
        duration=durations[text]
    )

    await state.set_state(
        MeditationForm.voice
    )

    await message.answer(
        "🎙 <b>Выберите голос медитации</b>\n\n"
        "👨 Мужской — спокойный низкий голос\n"
        "👩 Женский — мягкий расслабляющий голос",
        parse_mode="HTML",
        reply_markup=voice_keyboard,
    )

@router.message(MeditationForm.voice)
async def meditation_voice(
    message: Message,
    state: FSMContext,
):
    voices = {
        "👨 Мужской": "male",
        "👩 Женский": "female",
    }

    if message.text not in voices:
        await message.answer(
            "🎙 Выберите голос кнопкой ниже.",
            reply_markup=voice_keyboard,
        )
        return

    await state.update_data(
        voice=voices[message.text]
    )

    await state.set_state(
        MeditationForm.music
    )

