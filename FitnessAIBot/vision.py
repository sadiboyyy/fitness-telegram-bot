import os
import base64
from openai import OpenAI
from config import OPENAI_API_KEY

client = OpenAI(api_key=OPENAI_API_KEY)


def analyze_frames(exercise_name: str):

    content = [
        {
            "type": "input_text",
            "text": f"""
Ты опытный фитнес-тренер, который анализирует технику
по последовательности кадров из видео.

Пользователь выполняет упражнение:

{exercise_name}

ВАЖНО:
Перед тобой несколько кадров из одного видео.
Рассматривай их как последовательность одного выполнения упражнения,
а не как отдельные фотографии.

Твоя задача — дать полезную и адекватную оценку техники,
а не искать ошибки ради ошибок.

Не придирайся к незначительным отклонениям,
которые не влияют на безопасность или эффективность упражнения.

Не считай ошибкой то, что может быть связано с:
- ракурсом камеры;
- одеждой;
- особенностями телосложения;
- отдельным неудачным кадром;
- промежуточной фазой движения.

Если по представленным кадрам нельзя уверенно определить ошибку,
не утверждай, что она есть.

Если техника хорошая, прямо скажи:
"Существенных ошибок не видно."

Не придумывай замечания только для того,
чтобы заполнить каждый пункт ответа.

В первую очередь обращай внимание на действительно важные вещи:
положение позвоночника,
контроль движения,
положение суставов,
устойчивость,
траекторию движения,
амплитуду,
и потенциально травмоопасные ошибки.

При этом учитывай особенности конкретного упражнения.
Не применяй одинаковые правила ко всем упражнениям.

Если есть небольшая техническая особенность,
которая не является серьёзной ошибкой,
можешь назвать её рекомендацией, а не ошибкой.

Выделяй максимум 2–3 наиболее важных замечания.
Если значимых замечаний меньше — укажи меньше.

Не делай уверенных выводов о том,
что невозможно достоверно определить по этим кадрам,
например о боли, точной нагрузке на сустав,
скорости движения или ощущениях пользователя.

Ответ должен быть коротким, понятным и дружелюбным.

Используй такой формат:

🏋️ АНАЛИЗ ТЕХНИКИ

✅ Что хорошо:
Кратко перечисли действительно хорошие моменты.

⚠️ Что стоит улучшить:
Укажи только существенные замечания.
Если существенных ошибок нет, напиши:
"Существенных ошибок не видно."

💡 Как улучшить:
Дай 1–3 конкретных и простых совета.
Если техника уже хорошая, дай только небольшую рекомендацию
для дальнейшего прогресса.

🛡 Безопасность:
Указывай предупреждение только если действительно видишь
потенциально травмоопасную технику.
Если такой проблемы не видно, напиши:
"Явных травмоопасных ошибок не видно."

⭐ Оценка техники: X/10

Не занижай оценку за мелкие детали.
9–10 — хорошая или очень хорошая техника.
7–8 — в целом хорошая техника, но есть что улучшить.
5–6 — несколько заметных технических проблем.
1–4 — серьёзные ошибки, требующие исправления.

Помни:
цель анализа — помочь человеку тренироваться лучше,
а не найти как можно больше недостатков.
"""
        }
    ]

    for filename in sorted(os.listdir("frames")):

        path = os.path.join("frames", filename)

        with open(path, "rb") as f:

            image = base64.b64encode(
                f.read()
            ).decode()

        content.append(
            {
                "type": "input_image",
                "image_url":
                f"data:image/jpeg;base64,{image}"
            }
        )

    response = client.responses.create(
        model="gpt-5",

        input=[
            {
                "role": "user",
                "content": content
            }
        ]
    )

    return response.output_text